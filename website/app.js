  const buttonTimers = new WeakMap();

  function copyWithFeedback(text, btnElement, label = "Copied!") {
    if (!navigator.clipboard || !btnElement) return;
    navigator.clipboard.writeText(text).then(() => {
      const spanEl = btnElement.querySelector("span");
      if (!spanEl) return;

      if (!btnElement.dataset.origLabel) {
        btnElement.dataset.origLabel = spanEl.textContent;
      }

      if (buttonTimers.has(btnElement)) {
        clearTimeout(buttonTimers.get(btnElement));
      }

      spanEl.textContent = `✓ ${label}`;
      const timer = setTimeout(() => {
        spanEl.textContent = btnElement.dataset.origLabel;
        buttonTimers.delete(btnElement);
      }, 1600);

      buttonTimers.set(btnElement, timer);
    });
  }

