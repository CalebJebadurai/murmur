  function escapeHtml(text) {
    return text
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
  }

  function highlightSyntax(rawCode, lang) {
    const lines = rawCode.split("\n");

    return lines
      .map((line) => {
        const trimmed = line.trim();

        if (trimmed === "---") {
          return `<span class="syn-keyword">---</span>`;
        }

        if (
          trimmed.startsWith("<!--") ||
          (trimmed.startsWith("#") &&
            (line.includes("Compiled") ||
              line.includes("Generated") ||
              line.includes("Recipe") ||
              line.includes("Constraints") ||
              line.includes("Role:")))
        ) {
          return `<span class="syn-comment">${escapeHtml(line)}</span>`;
        }

        if (line.startsWith("#")) {
          const match = line.match(/^(#{1,6}\s+)(.*)$/);
          if (match) {
            return `<span class="syn-header">${escapeHtml(match[1])}</span><span class="syn-header-text">${escapeHtml(match[2])}</span>`;
          }
        }

        if (lang === "json") {
          let jsonLine = escapeHtml(line);
          jsonLine = jsonLine.replace(/"([^"]+)":/g, '<span class="syn-key">"$1"</span>:');
          jsonLine = jsonLine.replace(/: "([^"]*)"/g, ': <span class="syn-string">"$1"</span>');
          return jsonLine;
        }

        const yamlKeyVal = line.match(/^(\s*)([\w-]+)(:\s*)(.*)$/);
        if (yamlKeyVal && !trimmed.startsWith("-")) {
          const [, indent, key, colon, val] = yamlKeyVal;
          let coloredVal = escapeHtml(val);
          if (val.startsWith('"') || val.startsWith("'")) {
            coloredVal = `<span class="syn-string">${escapeHtml(val)}</span>`;
          } else if (["true", "false", "null", "strict"].includes(val.trim())) {
            coloredVal = `<span class="syn-keyword">${escapeHtml(val)}</span>`;
          } else if (/^\d+(\.\d+)*$/.test(val.trim())) {
            coloredVal = `<span class="syn-number">${escapeHtml(val)}</span>`;
          }
          return `${indent}<span class="syn-key">${escapeHtml(key)}</span>${colon}${coloredVal}`;
        }

        const bulletMatch = line.match(/^(\s*-\s+)(.*)$/);
        if (bulletMatch) {
          return `<span class="syn-bullet">${escapeHtml(bulletMatch[1])}</span>${escapeHtml(bulletMatch[2])}`;
        }

        return escapeHtml(line);
      })
      .join("\n");
  }

  function renderCodeWithGutter(rawCode, codeElement, gutterElement, lang = "markdown") {
    if (!codeElement || !gutterElement) return;
    const lines = rawCode.split("\n");
    gutterElement.innerHTML = lines.map((_, idx) => `<span>${idx + 1}</span>`).join("");
    codeElement.innerHTML = highlightSyntax(rawCode, lang);
  }

