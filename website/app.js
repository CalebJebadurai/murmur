  class StarlingBoid {
    constructor(x, y, maxW, maxH) {
      this.x = x;
      this.y = y;
      this.maxW = maxW;
      this.maxH = maxH;

      const angle = Math.random() * Math.PI * 2;
      const speed = 0.9 + Math.random() * 1.1;
      this.vx = Math.cos(angle) * speed;
      this.vy = Math.sin(angle) * speed;

      this.ax = 0;
      this.ay = 0;
      this.maxSpeed = 2.0;
      this.maxForce = 0.042;

      this.size = 2.0 + Math.random() * 1.4;
      this.colorIdx = Math.random();
      this.alpha = 0.35 + Math.random() * 0.4;
    }

    update(mouse) {
      if (mouse.active) {
        const dx = mouse.x - this.x;
        const dy = mouse.y - this.y;
        const dist = Math.hypot(dx, dy);

        if (dist < 200 && dist > 12) {
          const force = (1 - dist / 200) * 0.065;
          this.ax += (dx / dist) * force;
          this.ay += (dy / dist) * force;
        }
      }

      this.vx += this.ax;
      this.vy += this.ay;

      const speed = Math.hypot(this.vx, this.vy);
      if (speed > this.maxSpeed) {
        this.vx = (this.vx / speed) * this.maxSpeed;
        this.vy = (this.vy / speed) * this.maxSpeed;
      }

      this.x += this.vx;
      this.y += this.vy;
      this.ax = 0;
      this.ay = 0;

      const margin = 24;
      if (this.x < -margin) this.x = this.maxW + margin;
      if (this.x > this.maxW + margin) this.x = -margin;
      if (this.y < -margin) this.y = this.maxH + margin;
      if (this.y > this.maxH + margin) this.y = -margin;
    }

    applyFlock(boids) {
      let sepX = 0, sepY = 0, sepCount = 0;
      let aliX = 0, aliY = 0, aliCount = 0;
      let cohX = 0, cohY = 0, cohCount = 0;

      const sepDist = 28;
      const neighborDist = 68;

      for (let i = 0; i < boids.length; i++) {
        const other = boids[i];
        if (other === this) continue;

        const dx = other.x - this.x;
        const dy = other.y - this.y;
        const dist = Math.hypot(dx, dy);

        if (dist < sepDist && dist > 0) {
          sepX -= dx / dist;
          sepY -= dy / dist;
          sepCount++;
        }

        if (dist < neighborDist) {
          aliX += other.vx;
          aliY += other.vy;
          aliCount++;
          cohX += other.x;
          cohY += other.y;
          cohCount++;
        }
      }

      if (sepCount > 0) {
        sepX /= sepCount;
        sepY /= sepCount;
        const d = Math.hypot(sepX, sepY);
        if (d > 0) {
          sepX = (sepX / d) * this.maxSpeed - this.vx;
          sepY = (sepY / d) * this.maxSpeed - this.vy;
          this.ax += Math.max(-this.maxForce, Math.min(this.maxForce, sepX * 1.4));
          this.ay += Math.max(-this.maxForce, Math.min(this.maxForce, sepY * 1.4));
        }
      }

      if (aliCount > 0) {
        aliX /= aliCount;
        aliY /= aliCount;
        const d = Math.hypot(aliX, aliY);
        if (d > 0) {
          aliX = (aliX / d) * this.maxSpeed - this.vx;
          aliY = (aliY / d) * this.maxSpeed - this.vy;
          this.ax += Math.max(-this.maxForce, Math.min(this.maxForce, aliX * 0.85));
          this.ay += Math.max(-this.maxForce, Math.min(this.maxForce, aliY * 0.85));
        }
      }

      if (cohCount > 0) {
        cohX /= cohCount;
        cohY /= cohCount;
        const targetDx = cohX - this.x;
        const targetDy = cohY - this.y;
        const d = Math.hypot(targetDx, targetDy);
        if (d > 0) {
          const steerX = (targetDx / d) * this.maxSpeed - this.vx;
          const steerY = (targetDy / d) * this.maxSpeed - this.vy;
          this.ax += Math.max(-this.maxForce, Math.min(this.maxForce, steerX * 0.75));
          this.ay += Math.max(-this.maxForce, Math.min(this.maxForce, steerY * 0.75));
        }
      }
    }

    draw(ctx) {
      const angle = Math.atan2(this.vy, this.vx);
      ctx.save();
      ctx.translate(this.x, this.y);
      ctx.rotate(angle);

      const r = Math.round(56 + this.colorIdx * (129 - 56));
      const g = Math.round(189 - this.colorIdx * (189 - 140));
      const b = 248;

      ctx.fillStyle = `rgba(${r}, ${g}, ${b}, ${this.alpha})`;

      ctx.beginPath();
      ctx.moveTo(this.size * 2.1, 0);
      ctx.lineTo(-this.size * 1.4, -this.size * 0.85);
      ctx.lineTo(-this.size * 0.55, 0);
      ctx.lineTo(-this.size * 1.4, this.size * 0.85);
      ctx.closePath();
      ctx.fill();

      ctx.restore();
    }
  }

  function initStarlingCanvas() {
    const canvas = document.getElementById("starlingCanvas");
    const heroSection = document.getElementById("hero");
    if (!canvas || !heroSection) return;

    const ctx = canvas.getContext("2d");
    if (!ctx) return;

    let width = 0;
    let height = 0;
    const boids = [];

    function resizeCanvas() {
      const rect = heroSection.getBoundingClientRect();
      const dpr = Math.min(window.devicePixelRatio || 1, 2);
      width = rect.width;
      height = rect.height;
      canvas.width = Math.floor(width * dpr);
      canvas.height = Math.floor(height * dpr);
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

      boids.forEach((b) => {
        b.maxW = width;
        b.maxH = height;
      });
    }

    resizeCanvas();

    const boidsCount = Math.min(85, Math.max(40, Math.floor(width / 18)));
    for (let i = 0; i < boidsCount; i++) {
      boids.push(new StarlingBoid(Math.random() * width, Math.random() * height, width, height));
    }

    const mouse = { x: width / 2, y: height / 2, active: false };

    heroSection.addEventListener("mousemove", (e) => {
      const rect = heroSection.getBoundingClientRect();
      mouse.x = e.clientX - rect.left;
      mouse.y = e.clientY - rect.top;
      mouse.active = true;
    });

    heroSection.addEventListener("mouseleave", () => {
      mouse.active = false;
    });

    window.addEventListener("resize", resizeCanvas, { passive: true });

    const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (prefersReducedMotion) {
      ctx.clearRect(0, 0, width, height);
      boids.forEach((b) => b.draw(ctx));
      return;
    }

    let isVisible = true;
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          isVisible = entry.isIntersecting;
        });
      },
      { threshold: 0.05 }
    );
    observer.observe(heroSection);

    function animate() {
      if (isVisible) {
        ctx.clearRect(0, 0, width, height);

        ctx.lineWidth = 0.65;
        for (let i = 0; i < boids.length; i++) {
          for (let j = i + 1; j < boids.length; j++) {
            const dx = boids[i].x - boids[j].x;
            const dy = boids[i].y - boids[j].y;
            const dist = Math.hypot(dx, dy);

            if (dist < 56) {
              const lineAlpha = (1 - dist / 56) * 0.12;
              ctx.strokeStyle = `rgba(56, 189, 248, ${lineAlpha})`;
              ctx.beginPath();
              ctx.moveTo(boids[i].x, boids[i].y);
              ctx.lineTo(boids[j].x, boids[j].y);
              ctx.stroke();
            }
          }
        }

        for (let i = 0; i < boids.length; i++) {
          boids[i].applyFlock(boids);
          boids[i].update(mouse);
          boids[i].draw(ctx);
        }
      }
      requestAnimationFrame(animate);
    }

    requestAnimationFrame(animate);
  }

