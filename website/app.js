  function updatePlayground() {
    const sourceFileTag = document.getElementById("sourceFileTag");
    const sourceByteMeta = document.getElementById("sourceByteMeta");
    const sourceCodeView = document.querySelector("#sourceCodeView code");
    const sourceGutter = document.getElementById("sourceGutter");

    const compiledFileTag = document.getElementById("compiledFileTag");
    const compiledByteMeta = document.getElementById("compiledByteMeta");
    const compiledCodeView = document.querySelector("#compiledCodeView code");
    const compiledGutter = document.getElementById("compiledGutter");

    const sourceData = SOURCE_DOCS[currentSourceKey] || SOURCE_DOCS.analyst;
    if (sourceFileTag) sourceFileTag.textContent = sourceData.tag;
    if (sourceByteMeta) {
      const lineCount = sourceData.code.split("\n").length;
      const bytes = new Blob([sourceData.code]).size;
      sourceByteMeta.textContent = `${lineCount} lines • ${bytes} B`;
    }
    if (sourceCodeView && sourceGutter) {
      renderCodeWithGutter(sourceData.code, sourceCodeView, sourceGutter, sourceData.lang);
    }

    const targetMap = TARGET_OUTPUTS[currentSourceKey] || TARGET_OUTPUTS.analyst;
    const targetData = targetMap[currentTargetKey] || targetMap.copilot;

    if (compiledFileTag) compiledFileTag.textContent = targetData.file;
    if (compiledByteMeta) compiledByteMeta.textContent = "Illustrative output";
    if (compiledCodeView && compiledGutter) {
      renderCodeWithGutter(targetData.code, compiledCodeView, compiledGutter, targetData.lang);
    }
  }

